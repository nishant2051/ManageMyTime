test('stale edit from another tab cannot overwrite a newer task', async ({page,context}) => {
  await page.goto('/')
  await page.getByRole('button',{name:'Create task',exact:true}).click()
  await page.getByLabel('Task name').fill('Shared task')
  await page.getByRole('dialog').getByRole('button',{name:'Create task',exact:true}).click()
  await page.getByRole('button',{name:'Edit Shared task',exact:true}).click()
  const other = await context.newPage()
  await other.goto('/')
  await other.getByRole('button',{name:'Edit Shared task',exact:true}).click()
  await other.getByLabel('Task name').fill('Updated elsewhere')
  await other.getByRole('button',{name:'Save changes'}).click()
  await expect(other.getByRole('heading',{name:'Updated elsewhere'})).toBeVisible()
  await page.getByLabel('Task name').fill('Stale overwrite')
  await page.getByRole('button',{name:'Save changes'}).click()
  await expect(page.getByRole('alert')).toContainText('another tab')
  await page.getByRole('button',{name:'Cancel'}).click()
  await page.getByRole('button',{name:'Refresh list'}).click()
  await expect(page.getByRole('heading',{name:'Updated elsewhere'})).toBeVisible()
  await expect(page.getByRole('heading',{name:'Stale overwrite'})).toHaveCount(0)
})

test('unavailable storage shows a recoverable error without claiming success', async ({page}) => {
  await page.addInitScript(() => { Object.defineProperty(window, 'indexedDB', {value: undefined}) })
  await page.goto('/')
  await expect(page.getByRole('alert')).toContainText('storage is unavailable')
  await expect(page.getByRole('button',{name:'Create task',exact:true})).toBeDisabled()
  await expect(page.getByRole('button',{name:'Retry loading'})).toBeVisible()
})

 test('periodic, inactivity and grace preferences persist independently', async ({page}) => {
  await page.goto('/')
  await page.getByRole('button',{name:'Create task',exact:true}).click()
  await page.getByLabel('Task name').fill('Presence settings')
  await page.getByText('Confirmation settings',{exact:true}).click()
  await page.getByLabel('Enable periodic confirmation').check()
  await page.getByLabel('Periodic interval (minutes)',{exact:true}).fill('30')
  await page.getByLabel('Inactivity interval (minutes)',{exact:true}).fill('10')
  await page.getByLabel('Grace period (minutes)',{exact:true}).fill('2')
  await page.getByRole('dialog').getByRole('button',{name:'Create task',exact:true}).click()
  await expect(page.getByRole('heading',{name:'Presence settings',exact:true})).toBeVisible()
  await page.reload()
  await page.getByRole('button',{name:'Edit Presence settings',exact:true}).click()
  await page.getByText('Confirmation settings',{exact:true}).click()
  await expect(page.getByLabel('Periodic interval (minutes)',{exact:true})).toHaveValue('30')
  await expect(page.getByLabel('Inactivity interval (minutes)',{exact:true})).toHaveValue('10')
  await expect(page.getByLabel('Grace period (minutes)',{exact:true})).toHaveValue('2')
})
